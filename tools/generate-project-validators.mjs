/* Generate deterministic Ajv standalone validators from repository-owned schemas. */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const ROOT = new URL("../", import.meta.url);
const OUTPUT_URL = new URL("src/v100/generated/project-validators.mjs", ROOT);
const LIMITS_URL = new URL("schemas/limits.json", ROOT);
const VOCABULARIES_URL = new URL("schemas/vocabularies.json", ROOT);
export const PROJECT_SCHEMA_SPECS = [
  ["project0", "schemas/project/0.schema.json"],
  ["project1", "schemas/project/1.schema.json"],
  ["project2", "schemas/project/2.schema.json"],
  ["project3", "schemas/project/3.schema.json"],
  ["project4", "schemas/project/4.schema.json"],
  ["bundleManifest", "schemas/bundle-manifest.schema.json"],
];

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

export async function generateProjectValidatorSource() {
  const loaded = await Promise.all(PROJECT_SCHEMA_SPECS.map(async ([name, path]) => {
    const bytes = await readFile(new URL(path, ROOT));
    return { name, path, bytes, schema: JSON.parse(bytes) };
  }));
  const limitsBytes = await readFile(LIMITS_URL);
  const limits = JSON.parse(limitsBytes);
  const vocabulariesBytes = await readFile(VOCABULARIES_URL);
  const vocabularies = JSON.parse(vocabulariesBytes);
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    code: { esm: true, lines: true, optimize: true, source: true },
  });
  for (const { schema } of loaded) ajv.addSchema(schema);
  const exports = Object.fromEntries(loaded.map(({ name, schema }) => [name, schema.$id]));
  const validators = standaloneCode(ajv, exports)
    .replace(
      'const func1 = require("ajv/dist/runtime/ucs2length").default;',
      'import ucs2LengthModule from "ajv/dist/runtime/ucs2length.js";\nconst func1 = ucs2LengthModule.default;',
    )
    .trimEnd();
  const fingerprints = {
    bundle: sha256(loaded.find(({ name }) => name === "bundleManifest").bytes),
    project: Object.fromEntries(loaded
      .filter(({ name }) => name.startsWith("project"))
      .map(({ name, bytes }) => [name.slice("project".length), sha256(bytes)])),
  };
  return [
    "/* Generated by tools/generate-project-validators.mjs; do not edit directly. */",
    validators,
    `export const schemaFingerprints = Object.freeze(${JSON.stringify(fingerprints)});`,
    `export const limitsFingerprint = "${sha256(limitsBytes)}";`,
    `export const vocabulariesFingerprint = "${sha256(vocabulariesBytes)}";`,
    `export const contractLimits = Object.freeze(${JSON.stringify(limits)});`,
    // The vocabulary data lives beside the schema rather than inside it: a
    // foreign keyword in a JSON Schema is something every consumer has to be
    // taught about. A drift test asserts the schema enums equal these keys.
    `export const contractVocabularies = Object.freeze(${JSON.stringify(vocabularies)});`,
    "",
  ].join("\n");
}

async function main() {
  const expected = await generateProjectValidatorSource();
  if (process.argv.includes("--check")) {
    let actual = "";
    try {
      actual = await readFile(OUTPUT_URL, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (actual !== expected) {
      throw new Error("generated project validators are stale; run npm run generate:contract:validators");
    }
    return;
  }
  await writeFile(OUTPUT_URL, expected, "utf8");
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
