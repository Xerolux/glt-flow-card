/* Factory plant templates: fifteen ready-made schematics a user can load into
 * the designer and adapt. Entity bindings stay empty on purpose — a template
 * carries structure and wording, never a claim about someone's entities. */
const eq = (id, type, name, subtitle, x, y, w, h, fields = []) => ({
  id, type, name, subtitle, x, y, width: w, height: h,
  fields: fields.map((label) => ({ label, entity: "" })),
});
const pipe = (id, medium, points) => ({ id, medium, points });
const kpi = (name, icon) => ({ name, icon, entity: { entity: "" } });

const tpl = (id, name, description, title, subtitle, equipment, paths, kpis = []) => ({
  id, name, description,
  config: {
    type: "custom:glt-flow-card",
    title, subtitle,
    canvas: { width: 1600, height: 900, viewport_height: "auto", grid: true, grid_size: 40 },
    zoom: { enabled: true, min: 0.25, max: 4, wheel: true, controls: true },
    views: [{ id: "schematic", name, kind: "schematic", icon: "mdi:sitemap-outline" }],
    default_view: "schematic",
    replay: { enabled: true, hours: 168, step_minutes: 15, autoplay_ms: 850 },
    trend: { enabled: true, hours: 168, max_series: 8, height: 270 },
    kpis,
    equipment,
    paths,
    datapoints: [],
  },
});

